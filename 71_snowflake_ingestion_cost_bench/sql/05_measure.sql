-- 計測結果を集計し、「構成ごとの結果」と「1テーブルあたりの月額」の2つの表を出す
USE ROLE ACCOUNTADMIN;
USE DATABASE CM_KASAMA_COST_BENCH_DB;
USE SCHEMA PUBLIC;
USE WAREHOUSE CM_KASAMA_COST_BENCH_REFERENCE_WH;

-- 集計の対象は、terraform applyでDBを作った時刻以降の履歴だけにする
SET BENCH_START = (
    SELECT CREATED FROM INFORMATION_SCHEMA.DATABASES
    WHERE DATABASE_NAME = 'CM_KASAMA_COST_BENCH_DB'
);

-- 参照秒: 各テーブルを読んだCTASの、直近3回の平均
CREATE OR REPLACE TEMPORARY TABLE REFERENCE_SEC AS
SELECT
    REGEXP_SUBSTR(QUERY_TEXT, 'REF_([A-Z_]+)_([0-9]+[MG]B)', 1, 1, 'e', 1) AS CONFIG,
    REGEXP_SUBSTR(QUERY_TEXT, 'REF_([A-Z_]+)_([0-9]+[MG]B)', 1, 1, 'e', 2) AS SIZE,
    ROUND(AVG(TOTAL_ELAPSED_TIME) / 1000, 1) AS REFERENCE_SEC
FROM (
    SELECT
        QUERY_TEXT,
        TOTAL_ELAPSED_TIME,
        ROW_NUMBER() OVER (
            PARTITION BY REGEXP_SUBSTR(QUERY_TEXT, 'REF_[A-Z_]+_([0-9]+[MG]B)')
            ORDER BY START_TIME DESC
        ) AS RUN_NUMBER
    FROM
        TABLE(INFORMATION_SCHEMA.QUERY_HISTORY_BY_WAREHOUSE(
            WAREHOUSE_NAME => 'CM_KASAMA_COST_BENCH_REFERENCE_WH',
            END_TIME_RANGE_START => $BENCH_START,
            RESULT_LIMIT => 1000
        ))
    WHERE QUERY_TEXT LIKE 'CREATE OR REPLACE TRANSIENT TABLE REF_%' AND EXECUTION_STATUS = 'SUCCESS'
)
WHERE RUN_NUMBER <= 3
GROUP BY 1, 2;

-- Taskの取り込み秒: Taskが起動してから完了するまでの、直近3回の平均
CREATE OR REPLACE TEMPORARY TABLE TASK_SEC AS
SELECT
    SPLIT_PART(NAME, '_TASK_', 1) AS CONFIG,
    SPLIT_PART(NAME, '_TASK_', 2) AS SIZE,
    ROUND(AVG(DATEDIFF('millisecond', SCHEDULED_TIME, COMPLETED_TIME)) / 1000, 1) AS INGEST_SEC
FROM (
    SELECT
        NAME,
        SCHEDULED_TIME,
        COMPLETED_TIME,
        ROW_NUMBER() OVER (PARTITION BY NAME ORDER BY SCHEDULED_TIME DESC) AS RUN_NUMBER
    FROM
        TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
            SCHEDULED_TIME_RANGE_START => $BENCH_START,
            RESULT_LIMIT => 1000
        ))
    WHERE DATABASE_NAME = 'CM_KASAMA_COST_BENCH_DB' AND STATE = 'SUCCEEDED'
)
WHERE RUN_NUMBER <= 3
GROUP BY 1, 2;

-- Snowpipeの取り込み秒: S3に最後のファイルを置いてから、全ファイルの取り込みが終わるまで(3回の平均)
LIST @S3_STAGE/snowpipe/;
CREATE OR REPLACE TEMPORARY TABLE SNOWPIPE_FILES AS
SELECT
    REGEXP_SUBSTR("name", 'snowpipe/([0-9]+[MG]B)/', 1, 1, 'e', 1) AS SIZE,
    REGEXP_SUBSTR("name", 'snowpipe/([0-9]+[MG]B)/(run[0-9]+)/', 1, 1, 'e', 2) AS RUN,
    TO_TIMESTAMP_NTZ(REPLACE("last_modified", ' GMT', ''), 'DY, DD MON YYYY HH24:MI:SS') AS PUT_AT_UTC
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

CREATE OR REPLACE TEMPORARY TABLE SNOWPIPE_SEC AS
WITH LOADED AS (
    SELECT
        '10MB' AS SIZE,
        SPLIT_PART(FILE_NAME, '/', 1) AS RUN,
        CONVERT_TIMEZONE('UTC', LAST_LOAD_TIME)::TIMESTAMP_NTZ AS LOADED_AT_UTC
    FROM
        TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
            TABLE_NAME => 'SNOWPIPE_ORDERS_10MB', START_TIME => $BENCH_START
        ))
    WHERE STATUS = 'Loaded'
    UNION ALL
    SELECT
        '100MB' AS SIZE,
        SPLIT_PART(FILE_NAME, '/', 1) AS RUN,
        CONVERT_TIMEZONE('UTC', LAST_LOAD_TIME)::TIMESTAMP_NTZ AS LOADED_AT_UTC
    FROM
        TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
            TABLE_NAME => 'SNOWPIPE_ORDERS_100MB', START_TIME => $BENCH_START
        ))
    WHERE STATUS = 'Loaded'
    UNION ALL
    SELECT
        '1GB' AS SIZE,
        SPLIT_PART(FILE_NAME, '/', 1) AS RUN,
        CONVERT_TIMEZONE('UTC', LAST_LOAD_TIME)::TIMESTAMP_NTZ AS LOADED_AT_UTC
    FROM
        TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
            TABLE_NAME => 'SNOWPIPE_ORDERS_1GB', START_TIME => $BENCH_START
        ))
    WHERE STATUS = 'Loaded'
),

PER_RUN AS (
    SELECT
        F.SIZE,
        F.RUN,
        DATEDIFF('millisecond', MAX(F.PUT_AT_UTC), MAX(L.LOADED_AT_UTC)) AS MS
    FROM SNOWPIPE_FILES AS F
    INNER JOIN LOADED AS L ON F.SIZE = L.SIZE AND F.RUN = L.RUN
    GROUP BY 1, 2
)

SELECT
    'SNOWPIPE' AS CONFIG,
    SIZE,
    ROUND(AVG(MS) / 1000, 1) AS INGEST_SEC
FROM PER_RUN
GROUP BY 1, 2;

-- 取り込みCredits: 3回分の課金の合計を3で割る
CREATE OR REPLACE TEMPORARY TABLE INGEST_CREDITS AS
SELECT
    'USER_MANAGED' AS CONFIG,
    REGEXP_SUBSTR(WAREHOUSE_NAME, '([0-9]+[MG]B)') AS SIZE,
    SUM(CREDITS_USED_COMPUTE) / 3 AS CREDITS
FROM
    TABLE(INFORMATION_SCHEMA.WAREHOUSE_METERING_HISTORY(
        DATE_RANGE_START => $BENCH_START
    ))
WHERE WAREHOUSE_NAME LIKE 'CM_KASAMA_COST_BENCH_USER_MANAGED_TASK_%'
GROUP BY 1, 2
UNION ALL
SELECT
    'SERVERLESS',
    REGEXP_SUBSTR(TASK_NAME, '([0-9]+[MG]B)'),
    SUM(CREDITS_USED) / 3
FROM
    TABLE(INFORMATION_SCHEMA.SERVERLESS_TASK_HISTORY(
        DATE_RANGE_START => $BENCH_START
    ))
WHERE TASK_NAME LIKE 'SERVERLESS_TASK_%'
GROUP BY 1, 2
UNION ALL
-- PIPE_USAGE_HISTORYはPIPE_NAMEを指定しないとPipe名が空で返るため、Pipeごとに呼ぶ
SELECT
    'SNOWPIPE',
    '10MB',
    SUM(CREDITS_USED) / 3
FROM
    TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(
        DATE_RANGE_START => $BENCH_START, PIPE_NAME => 'SNOWPIPE_10MB'
    ))
UNION ALL
SELECT
    'SNOWPIPE',
    '100MB',
    SUM(CREDITS_USED) / 3
FROM
    TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(
        DATE_RANGE_START => $BENCH_START, PIPE_NAME => 'SNOWPIPE_100MB'
    ))
UNION ALL
SELECT
    'SNOWPIPE',
    '1GB',
    SUM(CREDITS_USED) / 3
FROM
    TABLE(INFORMATION_SCHEMA.PIPE_USAGE_HISTORY(
        DATE_RANGE_START => $BENCH_START, PIPE_NAME => 'SNOWPIPE_1GB'
    ));

CREATE OR REPLACE TEMPORARY TABLE RESULT AS
WITH I AS (
    SELECT * FROM TASK_SEC
    UNION ALL
    SELECT * FROM SNOWPIPE_SEC
)

SELECT
    R.CONFIG,
    R.SIZE,
    I.INGEST_SEC,
    COALESCE(C.CREDITS, 0) AS INGEST_CREDITS,
    R.REFERENCE_SEC
FROM REFERENCE_SEC AS R
LEFT JOIN I
    ON R.CONFIG = I.CONFIG AND R.SIZE = I.SIZE
LEFT JOIN INGEST_CREDITS AS C
    ON R.CONFIG = C.CONFIG AND R.SIZE = C.SIZE;

-- 表1: 構成ごとの結果
SELECT
    DECODE(
        CONFIG, 'EXTERNAL', '外部テーブル', 'USER_MANAGED', 'user-managed Task',
        'SERVERLESS', 'serverless Task', 'SNOWPIPE', 'Snowpipe'
    ) AS "構成",
    SIZE AS "サイズ",
    INGEST_SEC AS "取り込み秒",
    ROUND(INGEST_CREDITS, 6) AS "取り込みCredits",
    REFERENCE_SEC AS "参照秒"
FROM RESULT
ORDER BY DECODE(SIZE, '10MB', 1, '100MB', 2, 3), DECODE(CONFIG, 'EXTERNAL', 1, 'USER_MANAGED', 2, 'SERVERLESS', 3, 4);

-- 表2: 1テーブルあたりの月額(円)。1日のCredits = 取り込みCredits + 参照Credits(参照秒 × 1.35 ÷ 3600) × 参照回数
SELECT
    DECODE(
        CONFIG, 'EXTERNAL', '外部テーブル', 'USER_MANAGED', 'user-managed Task',
        'SERVERLESS', 'serverless Task', 'SNOWPIPE', 'Snowpipe'
    ) AS "構成",
    SIZE AS "サイズ",
    ROUND((INGEST_CREDITS + 1 * REFERENCE_SEC * 1.35 / 3600) * 688 * 30) AS "月額(参照1回/日)",
    ROUND((INGEST_CREDITS + 5 * REFERENCE_SEC * 1.35 / 3600) * 688 * 30) AS "月額(参照5回/日)",
    ROUND((INGEST_CREDITS + 20 * REFERENCE_SEC * 1.35 / 3600) * 688 * 30) AS "月額(参照20回/日)"
FROM RESULT
ORDER BY DECODE(SIZE, '10MB', 1, '100MB', 2, 3), DECODE(CONFIG, 'EXTERNAL', 1, 'USER_MANAGED', 2, 'SERVERLESS', 3, 4);
