-- 途中経過の確認。Taskの実行状態と、取り込み先の行数を表示する
USE ROLE ACCOUNTADMIN;
USE DATABASE CM_KASAMA_COST_BENCH_DB;
USE SCHEMA PUBLIC;
USE WAREHOUSE CM_KASAMA_COST_BENCH_REFERENCE_WH;

SELECT
    NAME,
    STATE,
    SCHEDULED_TIME,
    COMPLETED_TIME
FROM
    TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START => DATEADD('hour', -1, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 100
    ))
WHERE DATABASE_NAME = 'CM_KASAMA_COST_BENCH_DB'
ORDER BY SCHEDULED_TIME DESC;

